// Carries Glimm's description into the app.
//
//   node Tools/glimm/build.mjs           writes Packages/LumaUI/Sources/LumaKit/GlimmArt.swift
//   node Tools/glimm/build.mjs --check   fails if that file is not what spec.js gives now
//
// spec.js is the one place Glimm is described. The Swift file is that description as JSON, so the
// app needs no JavaScript; a test (Tools/test_glimm_spec.py) keeps the two from drifting apart.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spec } from './spec.js';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', '..', 'Packages', 'LumaUI', 'Sources', 'LumaKit', 'GlimmArt.swift');

export function swiftSource() {
  const sections = Object.entries(spec).map(([k, v]) => JSON.stringify(k) + ':' + JSON.stringify(v));
  const json = '{\n' + sections.join(',\n') + '\n}';
  if (json.includes('\\') || json.includes('"""')) throw new Error('the description holds a character the Swift literal cannot carry');
  return `// Generated by Tools/glimm/build.mjs from Tools/glimm/spec.js. Do not edit this file: change
// spec.js, look at the result with Tools/glimm/shots.mjs, then run the build again.

/// Glimm, described: the skeleton, the skin, the clothes, and the poses and gestures of each mood.
/// \`GlimmSpec\` reads it once; the drawing code is in GlimmRig.swift.
enum GlimmArt {
    static let json = #"""
${json}
"""#
}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = swiftSource();
  if (process.argv.includes('--check')) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== source) {
      console.error('GlimmArt.swift is not what Tools/glimm/spec.js gives. Run: node Tools/glimm/build.mjs');
      process.exit(1);
    }
    console.log('GlimmArt.swift matches spec.js');
  } else {
    writeFileSync(out, source);
    console.log('wrote', out, source.length, 'bytes');
  }
}
